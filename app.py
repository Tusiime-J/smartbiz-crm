def init_db():
    # Create the MVP tables automatically on first deployment.
    with psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10) as db:
        db.execute("""CREATE TABLE IF NOT EXISTS customers (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            phone TEXT NOT NULL DEFAULT '',
            email TEXT NOT NULL DEFAULT '',
            business TEXT NOT NULL DEFAULT '',
            notes TEXT NOT NULL DEFAULT '',
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""")
        db.execute("""CREATE TABLE IF NOT EXISTS sales (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
            title TEXT NOT NULL,
            amount DOUBLE PRECISION NOT NULL DEFAULT 0,
            stage TEXT NOT NULL DEFAULT 'Lead'
                CHECK(stage IN ('Lead','Proposal','Negotiation','Won','Lost')),
            expected_date TEXT NOT NULL DEFAULT '',
            notes TEXT NOT NULL DEFAULT '',
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""")
        db.execute("""CREATE TABLE IF NOT EXISTS followups (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
            title TEXT NOT NULL,
            due_date TEXT NOT NULL,
            notes TEXT NOT NULL DEFAULT '',
            completed INTEGER NOT NULL DEFAULT 0,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""")


