@app.route("/reports")
def reports():
    db = get_db()
    by_stage = db.execute("""
        SELECT stage, COUNT(*) AS count, COALESCE(SUM(amount),0) AS total
        FROM sales GROUP BY stage ORDER BY
        CASE stage WHEN 'Lead' THEN 1 WHEN 'Proposal' THEN 2
        WHEN 'Negotiation' THEN 3 WHEN 'Won' THEN 4 ELSE 5 END
    """).fetchall()
    total_won = db.execute("SELECT COALESCE(SUM(amount),0) AS total FROM sales WHERE stage='Won'").fetchone()["total"]
    total_pipeline = db.execute("SELECT COALESCE(SUM(amount),0) AS total FROM sales WHERE stage IN ('Lead','Proposal','Negotiation')").fetchone()["total"]
    return render_template("reports.html", by_stage=by_stage, total_won=total_won,
                           total_pipeline=total_pipeline)


